// Lambda@Edge.
//
// The four event types and when each one does not execute:
//
//	viewer request  - runs when CloudFront receives a request from a viewer,
//	                  before it checks the cache. It does not run when fetching
//	                  a custom error page.
//	origin request  - runs only when CloudFront forwards a request to the
//	                  origin. A cache hit does not run it.
//	origin response - runs after CloudFront receives a response from the
//	                  origin, even if the origin returned an error. It does not
//	                  run for a fresh cache hit or when the response was
//	                  generated by an origin request function.
//	viewer response - runs before returning the file to the viewer, whether or
//	                  not it came from the cache. It does not run when the
//	                  origin returns an HTTP status of 400 or higher, when a
//	                  custom error page is returned, or when the response was
//	                  generated by a viewer request function.
//
// "When a CloudFront event triggers the execution of a Lambda function, the
// function must finish before CloudFront can continue."
// https://docs.aws.amazon.com/AmazonCloudFront/latest/DeveloperGuide/lambda-cloudfront-trigger-events.html

// Lambda@Edge event types.
const (
	edgeViewerRequest  = "viewer-request"
	edgeOriginRequest  = "origin-request"
	edgeOriginResponse = "origin-response"
	edgeViewerResponse = "viewer-response"
)

// Lambda@Edge execution and body limits. The timeout applies to the run clock
// and the body limits are enforced on the request and the generated response.
//
// https://docs.aws.amazon.com/AmazonCloudFront/latest/DeveloperGuide/cloudfront-limits.html#limits-lambda-at-edge
// https://docs.aws.amazon.com/AmazonCloudFront/latest/DeveloperGuide/lambda-at-edge-function-restrictions.html
const (
	edgeViewerTimeout   = 5 * time.Second
	edgeOriginTimeout   = 30 * time.Second
	edgeViewerBodyLimit = 40 * 1024
	edgeOriginBodyLimit = 1 << 20
	edgeViewerB64Limit  = 53 * 1024
	edgeOriginB64Limit  = 1331 * 1024
)

// EdgeFunction is one LambdaFunctionAssociations entry resolved to an
// AWS::Lambda::Version in the assembly.
type EdgeFunction struct {
	EventType   string        `json:"eventType"`
	Version     string        `json:"version"`
	Function    string        `json:"function"`
	IncludeBody bool          `json:"includeBody,omitempty"`
	Timeout     time.Duration `json:"-"`
	Refusals    []string      `json:"refusals,omitempty"`
}

// Servable reports whether the association can run.
func (e *EdgeFunction) Servable() bool { return e != nil && len(e.Refusals) == 0 }

// EdgeInvoker invokes a Lambda@Edge function version through the runner's real
// function path.
type EdgeInvoker interface {
	InvokeEdge(ctx context.Context, versionLogicalID string, timeout time.Duration, payload []byte) ([]byte, error)
}

// EdgeEvent is the Lambda@Edge event object.
type EdgeEvent struct {
	Records []EdgeRecord `json:"Records"`
}

// EdgeRecord is one record.
type EdgeRecord struct {
	CF EdgeCF `json:"cf"`
}

// EdgeCF is the cf object.
type EdgeCF struct {
	Config   EdgeConfig    `json:"config"`
	Request  *EdgeRequest  `json:"request,omitempty"`
	Response *EdgeResponse `json:"response,omitempty"`
	Origin   *EdgeOrigin   `json:"origin,omitempty"`
}

// EdgeConfig is the config object.
type EdgeConfig struct {
	DistributionDomainName string `json:"distributionDomainName"`
	DistributionID         string `json:"distributionId"`
	EventType              string `json:"eventType"`
	RequestID              string `json:"requestId"`
}

// EdgeHeader is one header entry. Key is inserted with initial capitalization
// when a function omits it.
type EdgeHeader struct {
	Key   string `json:"key,omitempty"`
	Value string `json:"value"`
}

// EdgeRequest is the request object.
type EdgeRequest struct {
	ClientIP    string                  `json:"clientIp"`
	Headers     map[string][]EdgeHeader `json:"headers"`
	Method      string                  `json:"method"`
	Querystring string                  `json:"querystring"`
	URI         string                  `json:"uri"`
	Body        *EdgeBody               `json:"body,omitempty"`
	// Origin is the origin a returned request switches to. CloudFront resolves
	// the domain again and forwards to that origin.
	Origin *EdgeOrigin `json:"origin,omitempty"`
}

// EdgeResponse is the response object.
type EdgeResponse struct {
	Headers           map[string][]EdgeHeader `json:"headers"`
	Status            int                     `json:"status"`
	StatusDescription string                  `json:"statusDescription,omitempty"`
	Body              *EdgeBody               `json:"body,omitempty"`
}

// EdgeBody is the body object. A generated response may return the body as a
// plain JSON string instead of {encoding, data}; both forms are accepted.
type EdgeBody struct {
	InputTruncated bool   `json:"inputTruncated"`
	Action         string `json:"action,omitempty"`
	Encoding       string `json:"encoding,omitempty"`
	Data           string `json:"data,omitempty"`
}

// UnmarshalJSON accepts the object form and the plain-string body form.
func (b *EdgeBody) UnmarshalJSON(raw []byte) error {
	var text string
	if err := json.Unmarshal(raw, &text); err == nil {
		b.Action = "replace"
		b.Encoding = "text"
		b.Data = text
		return nil
	}
	type plain EdgeBody
	var decoded plain
	if err := json.Unmarshal(raw, &decoded); err != nil {
		return fmt.Errorf("body is neither a string nor an object: %w", err)
	}
	*b = EdgeBody(decoded)
	return nil
}

// EdgeOrigin is the origin object for origin events.
type EdgeOrigin struct {
	Custom *EdgeCustomOrigin `json:"custom,omitempty"`
	S3     *EdgeS3Origin     `json:"s3,omitempty"`
}

// EdgeCustomOrigin is a custom origin description.
type EdgeCustomOrigin struct {
	CustomHeaders             map[string][]EdgeHeader `json:"customHeaders,omitempty"`
	DomainName                string                  `json:"domainName"`
	Path                      string                  `json:"path"`
	Port                      int                     `json:"port"`
	Protocol                  string                  `json:"protocol"`
	ReadTimeout               int                     `json:"readTimeout,omitempty"`
	KeepaliveTimeout          int                     `json:"keepaliveTimeout,omitempty"`
	ResponseCompletionTimeout int                     `json:"responseCompletionTimeout,omitempty"`
	SSLProtocols              []string                `json:"sslProtocols,omitempty"`
}

// EdgeS3Origin is an S3 origin description.
type EdgeS3Origin struct {
	AuthMethod string `json:"authMethod"`
	Region     string `json:"region"`
	DomainName string `json:"domainName"`
	Path       string `json:"path"`
}

// EdgeOutcome is one function execution: it returned a request, a generated
// response, or (for response events) a replaced response.
type EdgeOutcome struct {
	Request  *EdgeRequest
	Response *EdgeResponse
	Logs     []string
}

// EdgeValidationError is an invalid object or body a function returned.
// CloudFront answers 502 for an incorrectly formed response:
// https://repost.aws/knowledge-center/lambda-edge-500-errors
type EdgeValidationError struct {
	Function string
	Reason   string
}

func (e *EdgeValidationError) Error() string {
	return fmt.Sprintf("Lambda@Edge function %s returned an invalid object: %s", e.Function, e.Reason)
}

// EdgeExecutionError is a function that threw or did not finish. CloudFront
// answers 503 for unhandled exceptions in the function code.
type EdgeExecutionError struct {
	Function string
	Reason   string
}

func (e *EdgeExecutionError) Error() string {
	return fmt.Sprintf("Lambda@Edge function %s failed: %s", e.Function, e.Reason)
}

// parseEdgeAssociations reads a behavior's LambdaFunctionAssociations. Each
// entry must name an AWS::Lambda::Version in the assembly; $LATEST, an alias
// and an unknown ARN are refused by name.
// https://docs.aws.amazon.com/CloudFormation/latest/UserGuide/aws-properties-cloudfront-distribution-lambdafunctionassociation.html
//
//nolint:gocyclo // one branch per association property and event type
func parseEdgeAssociations(
	raw json.RawMessage,
	stack string,
	index *resourceIndex,
	distributionID string,
) (map[string]*EdgeFunction, error) {
	var values []json.RawMessage
	if err := json.Unmarshal(raw, &values); err != nil {
		return nil, fmt.Errorf("%s: LambdaFunctionAssociations: %w", distributionID, err)
	}
	out := map[string]*EdgeFunction{}
	for position, value := range values {
		fields, err := decodeObject(value)
		if err != nil {
			return nil, fmt.Errorf("%s: LambdaFunctionAssociations[%d]: %w", distributionID, position, err)
		}
		association := &EdgeFunction{}
		for _, name := range sortedKeys(fields) {
			switch name {
			case "EventType":
				if err := json.Unmarshal(fields[name], &association.EventType); err != nil {
					return nil, fmt.Errorf("%s: LambdaFunctionAssociations[%d].EventType: %w", distributionID, position, err)
				}
			case "IncludeBody":
				if err := json.Unmarshal(fields[name], &association.IncludeBody); err != nil {
					return nil, fmt.Errorf("%s: LambdaFunctionAssociations[%d].IncludeBody: %w", distributionID, position, err)
				}
			case "LambdaFunctionARN":
				association.Version, association.Function, association.Refusals = resolveLambdaVersionRef(
					fields[name], stack, index, association.Refusals)
			default:
				association.Refusals = append(association.Refusals,
					fmt.Sprintf("LambdaFunctionAssociations[%d] property %q is not understood", position, name))
			}
		}
		switch association.EventType {
		case edgeViewerRequest, edgeViewerResponse:
			association.Timeout = edgeViewerTimeout
		case edgeOriginRequest, edgeOriginResponse:
			association.Timeout = edgeOriginTimeout
		case "":
			association.Refusals = append(association.Refusals, "LambdaFunctionAssociations entry has no EventType")
		default:
			association.Refusals = append(association.Refusals, fmt.Sprintf(
				"LambdaFunctionAssociations EventType %q is not viewer-request, origin-request, origin-response or viewer-response",
				association.EventType))
		}
		if association.IncludeBody && (association.EventType == edgeOriginResponse || association.EventType == edgeViewerResponse) {
			association.Refusals = append(association.Refusals,
				"IncludeBody is only valid on viewer-request and origin-request events; a response event never exposes the body")
		}
		if association.Version != "" {
			association.Refusals = append(association.Refusals, validateEdgeLambda(association.Version, stack, index)...)
		}
		if _, exists := out[association.EventType]; exists && association.EventType != "" {
			association.Refusals = append(association.Refusals,
				fmt.Sprintf("more than one Lambda@Edge function is associated with event type %q", association.EventType))
		}
		out[association.EventType] = association
	}
	return out, nil
}

// resolveLambdaVersionRef resolves a LambdaFunctionARN expression to an
// AWS::Lambda::Version and its function. "The function ARN must specify the ARN
// of a function version; you can't specify an alias or $LATEST."
//
//nolint:gocognit,gocyclo // one branch per ARN expression form
func resolveLambdaVersionRef(
	raw json.RawMessage,
	stack string,
	index *resourceIndex,
	refusals []string,
) (version, function string, out []string) {
	out = refusals
	var literal string
	if err := json.Unmarshal(raw, &literal); err == nil {
		switch {
		case strings.HasSuffix(literal, ":LATEST"):
			return "", "", append(out, "LambdaFunctionARN names $LATEST; Lambda@Edge requires a numbered function version")
		case strings.Contains(literal, ":function:") && strings.Contains(literal, ":live"):
			return "", "", append(out, "LambdaFunctionARN names an alias; Lambda@Edge requires a numbered function version")
		default:
			return "", "", append(out, fmt.Sprintf(
				"LambdaFunctionARN %q is a literal ARN; the local gateway resolves a Ref to an AWS::Lambda::Version in the assembly", literal))
		}
	}
	var expression map[string]json.RawMessage
	if err := json.Unmarshal(raw, &expression); err != nil || len(expression) != 1 {
		return "", "", append(out, "LambdaFunctionARN is not a resolvable expression")
	}
	for key, value := range expression {
		switch key {
		case "Ref":
			var id string
			if err := json.Unmarshal(value, &id); err != nil || id == "" {
				return "", "", append(out, "LambdaFunctionARN Ref has no logical id")
			}
			resource, found := index.lookup(stack, id)
			if !found || resource.Type != typeLambdaVersion {
				return "", "", append(out, fmt.Sprintf(
					"LambdaFunctionARN does not reference an AWS::Lambda::Version in this assembly (%s)", id))
			}
			qualified := index.qualified(stack, id)
			target, problem := lambdaVersionFunction(resource, stack, index)
			if problem != "" {
				return "", "", append(out, problem)
			}
			return qualified, target, out
		case valueFnGetAtt:
			id, attr, ok := getAtt(value)
			if !ok || attr != "FunctionArn" {
				return "", "", append(out, "LambdaFunctionARN Fn::GetAtt is not a Version FunctionArn")
			}
			resource, found := index.lookup(stack, id)
			if !found || resource.Type != typeLambdaVersion {
				return "", "", append(out, fmt.Sprintf(
					"LambdaFunctionARN does not reference an AWS::Lambda::Version in this assembly (%s)", id))
			}
			target, problem := lambdaVersionFunction(resource, stack, index)
			if problem != "" {
				return "", "", append(out, problem)
			}
			return index.qualified(stack, id), target, out
		default:
			return "", "", append(out, fmt.Sprintf(
				"LambdaFunctionARN expression %s does not resolve to an AWS::Lambda::Version", compactJSON(raw)))
		}
	}
	return "", "", out
}

// lambdaVersionFunction resolves an AWS::Lambda::Version FunctionName to the
// AWS::Lambda::Function it publishes.
func lambdaVersionFunction(resource Resource, stack string, index *resourceIndex) (string, string) {
	properties, err := decodeProperties(resource)
	if err != nil {
		return "", fmt.Sprintf("AWS::Lambda::Version properties are invalid: %v", err)
	}
	raw, ok := properties["FunctionName"]
	if !ok {
		return "", "AWS::Lambda::Version has no FunctionName"
	}
	var expression map[string]json.RawMessage
	if err := json.Unmarshal(raw, &expression); err != nil || len(expression) != 1 {
		return "", "AWS::Lambda::Version FunctionName is not a Ref to an AWS::Lambda::Function"
	}
	ref, ok := expression["Ref"]
	if !ok {
		return "", "AWS::Lambda::Version FunctionName is not a Ref to an AWS::Lambda::Function"
	}
	var id string
	if err := json.Unmarshal(ref, &id); err != nil || id == "" {
		return "", "AWS::Lambda::Version FunctionName Ref has no logical id"
	}
	functionResource, found := index.lookup(stack, id)
	if !found || functionResource.Type != typeLambdaFunction {
		return "", fmt.Sprintf("AWS::Lambda::Version FunctionName %s is not an AWS::Lambda::Function in this assembly", id)
	}
	return index.qualified(stack, id), ""
}

// validateEdgeLambda applies the Lambda@Edge restrictions page to the function
// behind a version.
//
// https://docs.aws.amazon.com/AmazonCloudFront/latest/DeveloperGuide/lambda-at-edge-function-restrictions.html
//
//nolint:gocognit,gocyclo // one branch per restriction on the Lambda@Edge page
func validateEdgeLambda(versionID, stack string, index *resourceIndex) []string {
	versionResource, found := index.byStack[stack][strings.TrimPrefix(strings.TrimPrefix(versionID, stack+"/"), "/")]
	if !found {
		return []string{fmt.Sprintf("function version %s is not in the assembly", versionID)}
	}
	functionID, problem := lambdaVersionFunction(versionResource, stack, index)
	if problem != "" {
		return []string{problem}
	}
	functionResource, ok := index.byStack[stack][strings.TrimPrefix(strings.TrimPrefix(functionID, stack+"/"), "/")]
	if !ok {
		return []string{fmt.Sprintf("function %s is not in the assembly", functionID)}
	}
	properties, err := decodeProperties(functionResource)
	if err != nil {
		return []string{fmt.Sprintf("function %s properties are invalid: %v", functionID, err)}
	}
	var refusals []string
	for _, name := range sortedKeys(properties) {
		raw := properties[name]
		switch name {
		case "PackageType":
			var packageType string
			_ = json.Unmarshal(raw, &packageType) //nolint:errcheck // a non-string package type is not Image
			if strings.EqualFold(packageType, "Image") {
				refusals = append(refusals, "the function uses a container image; Lambda@Edge does not support container images")
			}
		case "Architectures":
			var architectures []string
			_ = json.Unmarshal(raw, &architectures) //nolint:errcheck // a malformed list is not arm64
			for _, architecture := range architectures {
				if strings.EqualFold(architecture, "arm64") {
					refusals = append(refusals, "the function uses arm64; Lambda@Edge does not support arm64")
				}
			}
		case "VpcConfig":
			if !isEmptyValue(raw) {
				refusals = append(refusals, "the function has a VpcConfig; Lambda@Edge does not support VPC access")
			}
		case "DeadLetterConfig":
			if !isEmptyValue(raw) {
				refusals = append(refusals, "the function has a DeadLetterConfig; Lambda@Edge does not support dead letter queues")
			}
		case "Layers":
			if !isEmptyArray(raw) {
				refusals = append(refusals, "the function declares Layers; Lambda@Edge does not support layers")
			}
		case "ReservedConcurrentExecutions":
			if !isEmptyValue(raw) {
				refusals = append(refusals, "the function reserves concurrency; Lambda@Edge does not support provisioned or reserved concurrency")
			}
		case "Environment":
			if variables, ok := environmentVariables(raw); ok && len(variables) > 0 {
				refusals = append(refusals, fmt.Sprintf(
					"the function declares environment variables (%s); Lambda@Edge supports only reserved environment variables",
					strings.Join(sortedKeys(variables), ", ")))
			}
		case "EphemeralStorage":
			var storage struct {
				Size int `json:"Size"`
			}
			if storageErr := json.Unmarshal(raw, &storage); storageErr == nil && storage.Size > 512 {
				refusals = append(refusals, fmt.Sprintf(
					"the function requests %d MB of ephemeral storage; Lambda@Edge allows at most 512 MB", storage.Size))
			}
		case "Runtime":
			var runtime string
			_ = json.Unmarshal(raw, &runtime) //nolint:errcheck // a non-string runtime is refused below
			if runtime != "" && !edgeRuntimeSupported(runtime) {
				refusals = append(refusals, fmt.Sprintf(
					"runtime %q is not a Node.js or Python runtime; Lambda@Edge supports Node.js and Python only", runtime))
			}
		}
	}
	versionProperties, err := decodeProperties(versionResource)
	if err == nil {
		if raw, ok := versionProperties["ProvisionedConcurrencyConfig"]; ok && !isEmptyValue(raw) {
			refusals = append(refusals, "the version has a ProvisionedConcurrencyConfig; Lambda@Edge does not support provisioned concurrency")
		}
	}
	return refusals
}

func environmentVariables(raw json.RawMessage) (map[string]json.RawMessage, bool) {
	fields, err := decodeObject(raw)
	if err != nil {
		return nil, false
	}
	variables, ok := fields["Variables"]
	if !ok {
		return nil, false
	}
	parsed, err := decodeObject(variables)
	if err != nil {
		return nil, false
	}
	return parsed, true
}

func edgeRuntimeSupported(runtime string) bool {
	lower := strings.ToLower(runtime)
	return strings.HasPrefix(lower, "nodejs") || strings.HasPrefix(lower, "python")
}

// edgeEvent builds the documented event object for one event type.
// https://docs.aws.amazon.com/AmazonCloudFront/latest/DeveloperGuide/lambda-event-structure.html
func (g *Gateway) edgeEvent(
	association *EdgeFunction,
	state *requestState,
	requestID, domainName string,
	origin *DistributionOrigin,
	response *OriginResponse,
) *EdgeEvent {
	record := EdgeRecord{CF: EdgeCF{Config: EdgeConfig{
		DistributionDomainName: domainName,
		DistributionID:         localDistributionID(g.Distribution),
		EventType:              association.EventType,
		RequestID:              requestID,
	}}}
	record.CF.Request = edgeRequestFromState(state, association.IncludeBody, association.EventType == edgeViewerRequest)
	if response != nil {
		record.CF.Response = edgeResponseFromOrigin(response)
	}
	if association.EventType == edgeOriginRequest || association.EventType == edgeOriginResponse {
		record.CF.Origin = edgeOriginFromDistribution(origin)
	}
	return &EdgeEvent{Records: []EdgeRecord{record}}
}

func edgeRequestFromState(state *requestState, includeBody, viewerEvent bool) *EdgeRequest {
	request := &EdgeRequest{
		ClientIP:    state.ViewerIP,
		Headers:     edgeHeaders(state.Header, state.Host),
		Method:      state.Method,
		Querystring: state.RawQuery,
		URI:         state.URI,
	}
	if includeBody && len(state.Body) > 0 {
		limit := edgeOriginBodyLimit
		if viewerEvent {
			limit = edgeViewerBodyLimit
		}
		body := state.Body
		truncated := false
		if len(body) > limit {
			body = body[:limit]
			truncated = true
		}
		// "CloudFront always base64 encodes the request body before exposing it
		// to Lambda@Edge."
		request.Body = &EdgeBody{
			InputTruncated: truncated,
			Action:         "read-only",
			Encoding:       "base64",
			Data:           base64.StdEncoding.EncodeToString(body),
		}
	}
	return request
}

func edgeResponseFromOrigin(response *OriginResponse) *EdgeResponse {
	return &EdgeResponse{
		Headers:           edgeHeaders(response.Header, ""),
		Status:            response.StatusCode,
		StatusDescription: response.StatusDescription,
	}
}

// edgeHeaders renders a header set as lowercase keys mapping to arrays of
// {key, value}. A repeated header keeps one array entry per value.
func edgeHeaders(header http.Header, host string) map[string][]EdgeHeader {
	out := map[string][]EdgeHeader{}
	for name, values := range header {
		if strings.EqualFold(name, "Host") && host != "" {
			continue
		}
		lower := strings.ToLower(name)
		if lower == "content-length" {
			continue
		}
		entries := make([]EdgeHeader, 0, len(values))
		for _, value := range values {
			entries = append(entries, EdgeHeader{Key: http.CanonicalHeaderKey(name), Value: value})
		}
		out[lower] = entries
	}
	if host != "" {
		out["host"] = []EdgeHeader{{Key: "Host", Value: host}}
	}
	return out
}

//nolint:gocyclo // one branch per origin field CloudFront exposes
func edgeOriginFromDistribution(origin *DistributionOrigin) *EdgeOrigin {
	if origin == nil {
		return nil
	}
	path := origin.OriginPath
	if path == "" {
		path = "/"
	}
	if origin.Kind == OriginS3 || origin.S3 != nil {
		authMethod := "none"
		if origin.OriginAccessControl != "" || (origin.S3 != nil && origin.S3.OriginAccessIdentity != "") {
			authMethod = "origin-access-identity"
		}
		return &EdgeOrigin{S3: &EdgeS3Origin{
			AuthMethod: authMethod,
			Region:     "us-east-1",
			DomainName: origin.DomainName,
			Path:       path,
		}}
	}
	custom := &EdgeCustomOrigin{
		DomainName: origin.DomainName,
		Path:       path,
		Port:       80,
		Protocol:   "http",
	}
	if origin.Custom != nil {
		if origin.Custom.ProtocolPolicy == valueHTTPSOnly {
			custom.Protocol = valueHTTPS
			custom.Port = 443
		}
		if origin.Custom.HTTPPort != nil && custom.Protocol == "http" {
			custom.Port = *origin.Custom.HTTPPort
		}
		if origin.Custom.HTTPSPort != nil && custom.Protocol == valueHTTPS {
			custom.Port = *origin.Custom.HTTPSPort
		}
		if origin.Custom.ReadTimeout != nil {
			custom.ReadTimeout = *origin.Custom.ReadTimeout
		}
		if origin.Custom.KeepaliveSeconds != nil {
			custom.KeepaliveTimeout = *origin.Custom.KeepaliveSeconds
		}
		custom.SSLProtocols = origin.Custom.SSLProtocols
	}
	if len(origin.CustomHeaders) > 0 {
		custom.CustomHeaders = map[string][]EdgeHeader{}
		for name, value := range origin.CustomHeaders {
			custom.CustomHeaders[strings.ToLower(name)] = []EdgeHeader{{Key: name, Value: value}}
		}
	}
	return &EdgeOrigin{Custom: custom}
}

// invokeEdge runs one association and validates what it returned.
func (g *Gateway) invokeEdge(
	ctx context.Context,
	association *EdgeFunction,
	event *EdgeEvent,
) (*EdgeOutcome, error) {
	if g.EdgeInvoker == nil {
		return nil, &EdgeExecutionError{
			Function: association.Version,
			Reason:   "the runner registered no Lambda@Edge invoker for this assembly",
		}
	}
	payload, err := json.Marshal(event)
	if err != nil {
		return nil, fmt.Errorf("encode Lambda@Edge event: %w", err)
	}
	timeout := association.Timeout
	if timeout <= 0 {
		timeout = edgeViewerTimeout
	}
	runCtx, cancel := context.WithTimeout(ctx, timeout)
	defer cancel()
	raw, err := g.EdgeInvoker.InvokeEdge(runCtx, association.Version, timeout, payload)
	if err != nil {
		return nil, &EdgeExecutionError{Function: association.Version, Reason: err.Error()}
	}
	return decodeEdgeResponse(association, event, raw)
}

// lambdaEdgeEnvelope is the shape a Lambda handler returns: either the cf
// record object or a bare request/response object.
type lambdaEdgeEnvelope struct {
	Records           []EdgeRecord            `json:"Records"`
	Status            *int                    `json:"status"`
	StatusDescription string                  `json:"statusDescription"`
	Headers           map[string][]EdgeHeader `json:"headers"`
	Body              *EdgeBody               `json:"body"`
	URI               string                  `json:"uri"`
	Method            string                  `json:"method"`
	Querystring       string                  `json:"querystring"`
	Origin            *EdgeOrigin             `json:"origin"`
}

func decodeEdgeResponse(association *EdgeFunction, _ *EdgeEvent, raw []byte) (*EdgeOutcome, error) {
	var envelope lambdaEdgeEnvelope
	if err := json.Unmarshal(raw, &envelope); err != nil {
		return nil, &EdgeValidationError{Function: association.Version, Reason: "the response is not a JSON object"}
	}
	record := EdgeRecord{}
	if len(envelope.Records) > 0 {
		record = envelope.Records[0]
	}
	if record.CF.Response != nil {
		if err := validateEdgeResponseObject(association, record.CF.Response); err != nil {
			return nil, err
		}
		return &EdgeOutcome{Response: record.CF.Response}, nil
	}
	if record.CF.Request != nil {
		request, err := validateEdgeRequestObject(association, record.CF.Request)
		if err != nil {
			return nil, err
		}
		return &EdgeOutcome{Request: request}, nil
	}
	if envelope.Status != nil {
		response := &EdgeResponse{
			Status:            *envelope.Status,
			StatusDescription: envelope.StatusDescription,
			Headers:           envelope.Headers,
			Body:              envelope.Body,
		}
		if err := validateEdgeResponseObject(association, response); err != nil {
			return nil, err
		}
		return &EdgeOutcome{Response: response}, nil
	}
	if envelope.URI != "" || envelope.Method != "" {
		request, err := validateEdgeRequestObject(association, &EdgeRequest{
			Method:      envelope.Method,
			URI:         envelope.URI,
			Querystring: envelope.Querystring,
			Headers:     envelope.Headers,
			Body:        envelope.Body,
			Origin:      envelope.Origin,
		})
		if err != nil {
			return nil, err
		}
		return &EdgeOutcome{Request: request}, nil
	}
	return nil, &EdgeValidationError{Function: association.Version, Reason: "the response contains neither a request nor a response object"}
}

// validateEdgeRequestObject applies the event structure's read-only and
// read-write rules.
func validateEdgeRequestObject(association *EdgeFunction, request *EdgeRequest) (*EdgeRequest, error) {
	if request.Method == "" {
		return nil, &EdgeValidationError{Function: association.Version, Reason: "request.method is missing"}
	}
	if !strings.HasPrefix(request.URI, "/") {
		return nil, &EdgeValidationError{Function: association.Version, Reason: "request.uri must begin with a forward slash"}
	}
	if _, ok := request.Headers["set-cookie"]; ok {
		return nil, &EdgeValidationError{Function: association.Version, Reason: "a request object cannot carry a set-cookie header"}
	}
	headers := map[string][]EdgeHeader{}
	for name, entries := range request.Headers {
		lower := strings.ToLower(name)
		if strings.HasPrefix(lower, "cloudfront-") {
			return nil, &EdgeValidationError{Function: association.Version, Reason: fmt.Sprintf(
				"a viewer request function cannot add the %s header; CloudFront adds CloudFront-* headers after the viewer request event and returns 502", name)}
		}
		for position := range entries {
			if entries[position].Key == "" {
				entries[position].Key = http.CanonicalHeaderKey(name)
			}
		}
		headers[lower] = entries
	}
	request.Headers = headers
	return request, nil
}

func validateEdgeResponseObject(association *EdgeFunction, response *EdgeResponse) error {
	if response.Status < 200 || response.Status > 599 {
		return &EdgeValidationError{Function: association.Version, Reason: fmt.Sprintf(
			"response.status %d is not between 200 and 599", response.Status)}
	}
	if response.Body != nil {
		if response.Status == http.StatusNoContent && (response.Body.Data != "" || response.Body.Encoding != "") {
			return &EdgeValidationError{Function: association.Version, Reason: "a 204 response cannot have a body"}
		}
		if response.Body.Action != "" && response.Body.Action != valueReplace {
			return &EdgeValidationError{Function: association.Version, Reason: fmt.Sprintf(
				"response.body.action %q is not replace", response.Body.Action)}
		}
	}
	headers := map[string][]EdgeHeader{}
	for name, entries := range response.Headers {
		for position := range entries {
			if entries[position].Key == "" {
				entries[position].Key = http.CanonicalHeaderKey(name)
			}
		}
		headers[strings.ToLower(name)] = entries
	}
	response.Headers = headers
	return nil
}

// edgeGeneratedResponse turns a generated response object into an
// OriginResponse, enforcing the documented body limits. A body over the limit,
// or one whose status is out of range, is a 502:
// "If your Lambda@Edge function returns a body that exceeds these limits, your
// request will fail with an HTTP 502 status code (Lambda validation error)."
func (g *Gateway) edgeGeneratedResponse(association *EdgeFunction, response *EdgeResponse, originBody []byte) (OriginResponse, error) {
	limit := edgeOriginBodyLimit
	base64Limit := edgeOriginB64Limit
	if association.EventType == edgeViewerRequest {
		limit = edgeViewerBodyLimit
		base64Limit = edgeViewerB64Limit
	}
	body := originBody
	if response.Body != nil {
		switch strings.ToLower(response.Body.Encoding) {
		case "", valueText:
			if len(response.Body.Data) > limit {
				return OriginResponse{}, &EdgeValidationError{Function: association.Version, Reason: fmt.Sprintf(
					"the %s body replacement is %d bytes; CloudFront allows %d", association.EventType, len(response.Body.Data), limit)}
			}
			body = []byte(response.Body.Data)
		case valueBase64:
			decoded, err := base64.StdEncoding.DecodeString(response.Body.Data)
			if err != nil {
				return OriginResponse{}, &EdgeValidationError{Function: association.Version, Reason: "the body is not valid base64"}
			}
			if len(decoded) > base64Limit {
				return OriginResponse{}, &EdgeValidationError{Function: association.Version, Reason: fmt.Sprintf(
					"the %s base64 body replacement is %d bytes; CloudFront allows %d", association.EventType, len(decoded), base64Limit)}
			}
			body = decoded
		default:
			return OriginResponse{}, &EdgeValidationError{Function: association.Version, Reason: fmt.Sprintf(
				"body encoding %q is not text or base64", response.Body.Encoding)}
		}
	}
	header := http.Header{}
	for name, entries := range response.Headers {
		for _, entry := range entries {
			header.Add(name, entry.Value)
		}
	}
	status := response.Status
	if status == 0 {
		status = http.StatusOK
	}
	description := response.StatusDescription
	if description == "" {
		description = fmt.Sprintf("%d %s", status, http.StatusText(status))
	}
	return OriginResponse{StatusCode: status, StatusDescription: description, Header: header, Body: body}, nil
}

// edgeOriginDomain names the domain an origin object points at.
func edgeOriginDomain(origin *EdgeOrigin) string {
	switch {
	case origin == nil:
		return ""
	case origin.Custom != nil:
		return origin.Custom.DomainName
	case origin.S3 != nil:
		return origin.S3.DomainName
	default:
		return ""
	}
}

// resolveEdgeOrigin maps an origin object a function returned to an origin of
// the distribution. A domain the assembly does not declare is refused; the
// local gateway never reaches the internet.
func (g *Gateway) resolveEdgeOrigin(origin *EdgeOrigin) (string, bool) {
	domain := strings.ToLower(edgeOriginDomain(origin))
	if domain == "" || g.Distribution == nil {
		return "", false
	}
	for _, candidate := range g.Distribution.Origins {
		if strings.ToLower(candidate.DomainName) == domain {
			return candidate.ID, true
		}
	}
	return "", false
}

// applyEdgeRequest copies a returned request object back into the state. The
// method is read-only and the rewrite never re-selects the cache behavior.
func applyEdgeRequest(state *requestState, request *EdgeRequest) {
	state.URI = request.URI
	state.RawQuery = request.Querystring
	header := http.Header{}
	host := state.Host
	for name, entries := range request.Headers {
		lower := strings.ToLower(name)
		for _, entry := range entries {
			if lower == "host" {
				host = entry.Value
				continue
			}
			header.Add(lower, entry.Value)
		}
	}
	state.Header = header
	state.Host = host
	if request.Body != nil && request.Body.Action == "replace" {
		switch strings.ToLower(request.Body.Encoding) {
		case "", valueText:
			state.Body = []byte(request.Body.Data)
		case valueBase64:
			if decoded, err := base64.StdEncoding.DecodeString(request.Body.Data); err == nil {
				state.Body = decoded
			}
		}
	}
}
