'use strict';

// Lambda@Edge viewer-request.
//
// It rewrites a URI and its query string, proves the read-only header key
// insertion rule (a returned header without a key gets initial capitalization),
// exposes an IncludeBody base64 body, and generates a response for one path.
// The request method is read-only and never changes here.
exports.handler = async (event) => {
    const cf = event.Records[0].cf;
    const request = cf.request;

    if (request.uri === '/edge/rewrite') {
        // The rewrite must not re-select the cache behavior: the gateway keeps
        // the behavior it selected for the original URI.
        request.uri = '/edge/rewritten';
        request.querystring = 'from=edge';
    }

    if (request.uri === '/edge/viewer-generated') {
        return {
            status: 200,
            statusDescription: 'OK',
            headers: {
                'content-type': [{ key: 'Content-Type', value: 'text/plain' }],
                'x-edge-generated': [{ key: 'X-Edge-Generated', value: 'viewer-request' }],
            },
            body: 'generated by the viewer-request function',
        };
    }

    // No key: CloudFront inserts the name with initial capitalization.
    request.headers['x-edge-viewer-request'] = [{ value: 'seen' }];

    if (request.body && request.body.data) {
        request.headers['x-edge-viewer-body-length'] = [{
            key: 'X-Edge-Viewer-Body-Length',
            value: String(Buffer.from(request.body.data, 'base64').length),
        }];
        request.headers['x-edge-viewer-body-truncated'] = [{
            key: 'X-Edge-Viewer-Body-Truncated',
            value: String(request.body.inputTruncated),
        }];
    }

    return request;
};
